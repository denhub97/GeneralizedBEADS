function [EntNorm, States] = opt_connected_tripartite(DensityOp, Padd, PaddVectors, OptTol, pauli_1x, pauli_1y, pauli_1z, ...
                                                      pauli_2x, pauli_2y, pauli_2z, ...
                                                      pauli_3x, pauli_3y, pauli_3z, ...
                                                      pauli_1x_2x, pauli_1x_2y, pauli_1x_2z, ...
                                                      pauli_1y_2x, pauli_1y_2y, pauli_1y_2z, ...
                                                      pauli_1z_2x, pauli_1z_2y, pauli_1z_2z, ...
                                                      pauli_1x_3x, pauli_1x_3y, pauli_1x_3z, ...
                                                      pauli_1y_3x, pauli_1y_3y, pauli_1y_3z, ...
                                                      pauli_1z_3x, pauli_1z_3y, pauli_1z_3z, ...
                                                      pauli_2x_3x, pauli_2x_3y, pauli_2x_3z, ...
                                                      pauli_2y_3x, pauli_2y_3y, pauli_2y_3z, ...
                                                      pauli_2z_3x, pauli_2z_3y, pauli_2z_3z, ...
                                                      pauli_1x_2x_3x, pauli_1x_2x_3y, pauli_1x_2x_3z, ...
                                                      pauli_1x_2y_3x, pauli_1x_2y_3y, pauli_1x_2y_3z, ...
                                                      pauli_1x_2z_3x, pauli_1x_2z_3y, pauli_1x_2z_3z, ...
                                                      pauli_1y_2x_3x, pauli_1y_2x_3y, pauli_1y_2x_3z, ...
                                                      pauli_1y_2y_3x, pauli_1y_2y_3y, pauli_1y_2y_3z, ...
                                                      pauli_1y_2z_3x, pauli_1y_2z_3y, pauli_1y_2z_3z, ...
                                                      pauli_1z_2x_3x, pauli_1z_2x_3y, pauli_1z_2x_3z, ...
                                                      pauli_1z_2y_3x, pauli_1z_2y_3y, pauli_1z_2y_3z, ...
                                                      pauli_1z_2z_3x, pauli_1z_2z_3y, pauli_1z_2z_3z)

    %!!! Optimization function for finding the pure state decomposition of
    %    a tripartite density operator with the smallest tripartite
    %    connected correlation function norm. The coefficients of a unitary
    %    mixing the eigenstates of the density operator are optimized, using
    %    the Frobenius norm of the connected correlations as cost function
    %    (see connected_norm_tripartite). The Pauli operators are passed in
    %    precomputed form to avoid recomputing them in every function call.
    %    The optimization tolerance is controlled by OptTol
    %
    %    input: DensityOp: The 8x8 density operator describing the
    %                      tripartite state
    %           Padd: Shall the decomposition be padded with additional
    %                 (zero) states (boolean)
    %           PaddVectors: Number of additional states for padding
    %           OptTol: Tolerance of the optimization (used as step
    %                   tolerance TolX and function tolerance TolFun of
    %                   fminunc, e.g., 1e-6)
    %           pauli_*: Precomputed Pauli operators of the 3-qubit
    %                    system, the name encodes the qubits and Pauli
    %                    matrices, e.g., pauli_1x_3z = sigma_x (x) 1 (x)
    %                    sigma_z
    %
    %    output: EntNorm: The tripartite connected correlation function
    %                     norm of the optimized decomposition
    %            States: The cell array of pure states (including their
    %                    weights) constituting the optimal decomposition

    % Optimization function in order to find the
    % decomposition of rho with the least amount of entanglement by using
    % the frobenius norm of rho-connected as a cost-function.
    dim = size(DensityOp,1);

    % Start with an eigendecomposition of rho in order to have a convenient
    % starting point (basis vectors)
    [eigenv,eigenvals] = eig(DensityOp);
    eigenvalues = diag(eigenvals);

    % Find non-zero eigenvalues and their indices in order to have the
    % number of basis states equal the rank of rho, but set a tolerance
    % otherwise it's too close to zero
    tolerance = 10e-8;
    non_zero_indices = find(eigenvalues>tolerance);

    % Concatenate eigenvectors corresponding to non-zero eigenvalues
    nonzero_eigenvectors = [eigenv(:,non_zero_indices)];
    nonzero_eigenvalues = [eigenvalues(non_zero_indices)];
    rank_rho = length(nonzero_eigenvalues);

    % Create eigenstates by multiplying the square root of the eigenvalue
    % with the corresponding eigenvector
    eigenstates = nonzero_eigenvectors .* sqrt(nonzero_eigenvalues)';

    % Pad the set of eigenstates with zero vectors to allow decompositions
    % with more pure states than the rank of the density operator
    if Padd
        for ii = rank_rho+1 : rank_rho+PaddVectors
            if PaddVectors <= 0
                break;
            end
            eigenstates(:,ii) = 0;
        end
        rank_rho = rank_rho+PaddVectors;
    end

    % Randomly initialize the coefficients for the unitary
    U_ini = rand(1,rank_rho^2)';

    % Optimization options, the tolerances are set by OptTol
    Options = optimset('HessUpdate','lbfgs','TolX',OptTol, ...
        'TolFun',OptTol,'MaxIter', 5000, 'display','iter', 'UseParallel',true, ...
        'MaxFunEvals',1e10, 'GradObj', 'off', 'LargeScale', 'off', ...
        'DerivativeCheck', 'off');

    % Optimize the unitary coefficients, i.e., the decomposition
    calc = @(U_coeff) connected_norm_tripartite(U_coeff,eigenstates,rank_rho,dim, pauli_1x, pauli_1y, pauli_1z, ...
                                                                                  pauli_2x, pauli_2y, pauli_2z, ...
                                                                                  pauli_3x, pauli_3y, pauli_3z, ...
                                                                                  pauli_1x_2x, pauli_1x_2y, pauli_1x_2z, ...
                                                                                  pauli_1y_2x, pauli_1y_2y, pauli_1y_2z, ...
                                                                                  pauli_1z_2x, pauli_1z_2y, pauli_1z_2z, ...
                                                                                  pauli_1x_3x, pauli_1x_3y, pauli_1x_3z, ...
                                                                                  pauli_1y_3x, pauli_1y_3y, pauli_1y_3z, ...
                                                                                  pauli_1z_3x, pauli_1z_3y, pauli_1z_3z, ...
                                                                                  pauli_2x_3x, pauli_2x_3y, pauli_2x_3z, ...
                                                                                  pauli_2y_3x, pauli_2y_3y, pauli_2y_3z, ...
                                                                                  pauli_2z_3x, pauli_2z_3y, pauli_2z_3z, ...
                                                                                  pauli_1x_2x_3x, pauli_1x_2x_3y, pauli_1x_2x_3z, ...
                                                                                  pauli_1x_2y_3x, pauli_1x_2y_3y, pauli_1x_2y_3z, ...
                                                                                  pauli_1x_2z_3x, pauli_1x_2z_3y, pauli_1x_2z_3z, ...
                                                                                  pauli_1y_2x_3x, pauli_1y_2x_3y, pauli_1y_2x_3z, ...
                                                                                  pauli_1y_2y_3x, pauli_1y_2y_3y, pauli_1y_2y_3z, ...
                                                                                  pauli_1y_2z_3x, pauli_1y_2z_3y, pauli_1y_2z_3z, ...
                                                                                  pauli_1z_2x_3x, pauli_1z_2x_3y, pauli_1z_2x_3z, ...
                                                                                  pauli_1z_2y_3x, pauli_1z_2y_3y, pauli_1z_2y_3z, ...
                                                                                  pauli_1z_2z_3x, pauli_1z_2z_3y, pauli_1z_2z_3z);
    [U_opt, cost_final, exitflag, output] = fminunc(calc, U_ini, Options);

    % Evaluate the connected correlation norm and the states for the
    % optimized coefficients
    [EntNorm,States] = connected_norm_tripartite(U_opt,eigenstates,rank_rho,dim, pauli_1x, pauli_1y, pauli_1z, ...
                                                                                 pauli_2x, pauli_2y, pauli_2z, ...
                                                                                 pauli_3x, pauli_3y, pauli_3z, ...
                                                                                 pauli_1x_2x, pauli_1x_2y, pauli_1x_2z, ...
                                                                                 pauli_1y_2x, pauli_1y_2y, pauli_1y_2z, ...
                                                                                 pauli_1z_2x, pauli_1z_2y, pauli_1z_2z, ...
                                                                                 pauli_1x_3x, pauli_1x_3y, pauli_1x_3z, ...
                                                                                 pauli_1y_3x, pauli_1y_3y, pauli_1y_3z, ...
                                                                                 pauli_1z_3x, pauli_1z_3y, pauli_1z_3z, ...
                                                                                 pauli_2x_3x, pauli_2x_3y, pauli_2x_3z, ...
                                                                                 pauli_2y_3x, pauli_2y_3y, pauli_2y_3z, ...
                                                                                 pauli_2z_3x, pauli_2z_3y, pauli_2z_3z, ...
                                                                                 pauli_1x_2x_3x, pauli_1x_2x_3y, pauli_1x_2x_3z, ...
                                                                                 pauli_1x_2y_3x, pauli_1x_2y_3y, pauli_1x_2y_3z, ...
                                                                                 pauli_1x_2z_3x, pauli_1x_2z_3y, pauli_1x_2z_3z, ...
                                                                                 pauli_1y_2x_3x, pauli_1y_2x_3y, pauli_1y_2x_3z, ...
                                                                                 pauli_1y_2y_3x, pauli_1y_2y_3y, pauli_1y_2y_3z, ...
                                                                                 pauli_1y_2z_3x, pauli_1y_2z_3y, pauli_1y_2z_3z, ...
                                                                                 pauli_1z_2x_3x, pauli_1z_2x_3y, pauli_1z_2x_3z, ...
                                                                                 pauli_1z_2y_3x, pauli_1z_2y_3y, pauli_1z_2y_3z, ...
                                                                                 pauli_1z_2z_3x, pauli_1z_2z_3y, pauli_1z_2z_3z);

    % Set small values to zero and normalize phase wrt biggest value
    tolerance = 1e-8;

    for k = 1:size(States,1)
        % Set entries smaller than tolerance to zero
        solutionk = States{k};
        solutionk(abs(solutionk)<tolerance) = 0;

        % Find the entry with the largest absolute value
        [max_value, idx] = max(abs(solutionk));
        max_element = solutionk(idx);

        % Calculate the phase of the maximum element
        max_element_phase = angle(max_element);

        % Adjust the phase of the entire vector to set the phase of max element to zero
        solutionk = solutionk * exp(-1i * max_element_phase);

        States{k} = solutionk;
    end

    % Sort the position of the arrays within the cell array States for
    % better compatibility with other final states from other optimizations

    % Create a matrix to store the real parts of the first entries and their indices
    first_entry_real_parts = zeros(size(States, 1), 2);

    % Extract the real parts of the first entries
    for k = 1:size(States, 1)
        solutionk = States{k};
        first_entry_real_parts(k, :) = [real(solutionk(1)), k];
    end

    % Sort based on the real parts in descending order
    sorted_entries = sortrows(first_entry_real_parts, -1);

    % Create a new cell array to store the sorted States
    sorted_final_states = cell(size(States));

    % Reorder the States based on the sorted indices
    for k = 1:size(States, 1)
        sorted_final_states{k} = States{sorted_entries(k, 2)};
    end

    % Update the original States with sorted States
    States = sorted_final_states;
end
