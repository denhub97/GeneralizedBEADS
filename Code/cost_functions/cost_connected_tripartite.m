function [EntNorm] = cost_connected_tripartite(DensityOp, pauli_1x, pauli_1y, pauli_1z, ...
                                                       pauli_2x, pauli_2y, pauli_2z, ...
                                                       pauli_3x, pauli_3y, pauli_3z, ...
                                                       pauli_1x_2x, pauli_1x_2y, pauli_1x_2z, ...
                                                       pauli_1y_2x, pauli_1y_2y, pauli_1y_2z, ...
                                                       pauli_1z_2x, pauli_1z_2y, pauli_1z_2z, ...
                                                       pauli_1x_3x, pauli_1x_3y, pauli_1x_3z, ...
                                                       pauli_1y_3x, pauli_1y_3y, pauli_1y_3z, ...
                                                       pauli_1z_3x, pauli_1z_3y, pauli_1z_3z, ...
                                                       pauli_2x_3x, pauli_2x_3y, pauli_2x_3z, ...
                                                       pauli_2y_3x, pauli_2y_3y, pauli_2y_3z, ...
                                                       pauli_2z_3x, pauli_2z_3y, pauli_2z_3z, ...
                                                       pauli_1x_2x_3x, pauli_1x_2x_3y, pauli_1x_2x_3z, ...
                                                       pauli_1x_2y_3x, pauli_1x_2y_3y, pauli_1x_2y_3z, ...
                                                       pauli_1x_2z_3x, pauli_1x_2z_3y, pauli_1x_2z_3z, ...
                                                       pauli_1y_2x_3x, pauli_1y_2x_3y, pauli_1y_2x_3z, ...
                                                       pauli_1y_2y_3x, pauli_1y_2y_3y, pauli_1y_2y_3z, ...
                                                       pauli_1y_2z_3x, pauli_1y_2z_3y, pauli_1y_2z_3z, ...
                                                       pauli_1z_2x_3x, pauli_1z_2x_3y, pauli_1z_2x_3z, ...
                                                       pauli_1z_2y_3x, pauli_1z_2y_3y, pauli_1z_2y_3z, ...
                                                       pauli_1z_2z_3x, pauli_1z_2z_3y, pauli_1z_2z_3z)

    %!!! Cost function for calculating the tripartite connected correlation
    %    function norm of a 3-qubit density operator. The density operator is
    %    expanded in the Pauli basis and all contributions which can be
    %    expressed by lower-order correlations (local expectation values and
    %    two-qubit correlations) are subtracted. The Frobenius norm of the
    %    remainder is the norm of the connected three-qubit correlations.
    %    All Pauli operators and their products are passed in precomputed
    %    form to avoid recomputing them in every function call
    %
    %    input: DensityOp: The 8x8 density operator describing the
    %                      tripartite state
    %           pauli_*: Precomputed Pauli operators of the 3-qubit
    %                    system, the name encodes the qubits and Pauli
    %                    matrices, e.g., pauli_1x_3z = sigma_x (x) Id (x)
    %                    sigma_z
    %
    %    output: EntNorm: The tripartite connected correlation function
    %                     norm

    % Expectation values of the single-qubit and two-qubit Pauli operators
    % which are needed for the correlation analysis
    persistent exp_pauli_1x exp_pauli_1y exp_pauli_1z ...
               exp_pauli_2x exp_pauli_2y exp_pauli_2z ...
               exp_pauli_3x exp_pauli_3y exp_pauli_3z ...
               exp_pauli_1x_2x exp_pauli_1x_2y exp_pauli_1x_2z ...
               exp_pauli_1y_2x exp_pauli_1y_2y exp_pauli_1y_2z ...
               exp_pauli_1z_2x exp_pauli_1z_2y exp_pauli_1z_2z ...
               exp_pauli_1x_3x exp_pauli_1x_3y exp_pauli_1x_3z ...
               exp_pauli_1y_3x exp_pauli_1y_3y exp_pauli_1y_3z ...
               exp_pauli_1z_3x exp_pauli_1z_3y exp_pauli_1z_3z ...
               exp_pauli_2x_3x exp_pauli_2x_3y exp_pauli_2x_3z ...
               exp_pauli_2y_3x exp_pauli_2y_3y exp_pauli_2y_3z ...
               exp_pauli_2z_3x exp_pauli_2z_3y exp_pauli_2z_3z

    % Calculate the expectation values beforehand
    % Expectation values of single-qubit operators
    exp_pauli_1x = trace(DensityOp * pauli_1x);
    exp_pauli_1y = trace(DensityOp * pauli_1y);
    exp_pauli_1z = trace(DensityOp * pauli_1z);

    exp_pauli_2x = trace(DensityOp * pauli_2x);
    exp_pauli_2y = trace(DensityOp * pauli_2y);
    exp_pauli_2z = trace(DensityOp * pauli_2z);

    exp_pauli_3x = trace(DensityOp * pauli_3x);
    exp_pauli_3y = trace(DensityOp * pauli_3y);
    exp_pauli_3z = trace(DensityOp * pauli_3z);

    % Expectation values of operators acting on qubits 1 and 2
    exp_pauli_1x_2x = trace(DensityOp * pauli_1x_2x);
    exp_pauli_1x_2y = trace(DensityOp * pauli_1x_2y);
    exp_pauli_1x_2z = trace(DensityOp * pauli_1x_2z);

    exp_pauli_1y_2x = trace(DensityOp * pauli_1y_2x);
    exp_pauli_1y_2y = trace(DensityOp * pauli_1y_2y);
    exp_pauli_1y_2z = trace(DensityOp * pauli_1y_2z);

    exp_pauli_1z_2x = trace(DensityOp * pauli_1z_2x);
    exp_pauli_1z_2y = trace(DensityOp * pauli_1z_2y);
    exp_pauli_1z_2z = trace(DensityOp * pauli_1z_2z);

    % Expectation values of operators acting on qubits 1 and 3
    exp_pauli_1x_3x = trace(DensityOp * pauli_1x_3x);
    exp_pauli_1x_3y = trace(DensityOp * pauli_1x_3y);
    exp_pauli_1x_3z = trace(DensityOp * pauli_1x_3z);

    exp_pauli_1y_3x = trace(DensityOp * pauli_1y_3x);
    exp_pauli_1y_3y = trace(DensityOp * pauli_1y_3y);
    exp_pauli_1y_3z = trace(DensityOp * pauli_1y_3z);

    exp_pauli_1z_3x = trace(DensityOp * pauli_1z_3x);
    exp_pauli_1z_3y = trace(DensityOp * pauli_1z_3y);
    exp_pauli_1z_3z = trace(DensityOp * pauli_1z_3z);

    % Expectation values of operators acting on qubits 2 and 3
    exp_pauli_2x_3x = trace(DensityOp * pauli_2x_3x);
    exp_pauli_2x_3y = trace(DensityOp * pauli_2x_3y);
    exp_pauli_2x_3z = trace(DensityOp * pauli_2x_3z);

    exp_pauli_2y_3x = trace(DensityOp * pauli_2y_3x);
    exp_pauli_2y_3y = trace(DensityOp * pauli_2y_3y);
    exp_pauli_2y_3z = trace(DensityOp * pauli_2y_3z);

    exp_pauli_2z_3x = trace(DensityOp * pauli_2z_3x);
    exp_pauli_2z_3y = trace(DensityOp * pauli_2z_3y);
    exp_pauli_2z_3z = trace(DensityOp * pauli_2z_3z);

    % Start with the full density operator, from which all contributions
    % which can be written in terms of lower-order correlations are
    % subtracted. The Pauli expansion of the density operator reads
    % rho = 1/8 * sum_P <P> P over all Pauli strings P
    rho_ = DensityOp;

    % Subtract the local contributions with expectation values of a single
    % qubit
    % Qubit 1
    rho_ = rho_ - 1/8*( ...
        exp_pauli_1x*pauli_1x+...
        exp_pauli_1y*pauli_1y+...
        exp_pauli_1z*pauli_1z);

    % Qubit 2
    rho_ = rho_ - 1/8*( ...
        exp_pauli_2x*pauli_2x+...
        exp_pauli_2y*pauli_2y+...
        exp_pauli_2z*pauli_2z);

    % Qubit 3
    rho_ = rho_ - 1/8*( ...
        exp_pauli_3x*pauli_3x+...
        exp_pauli_3y*pauli_3y+...
        exp_pauli_3z*pauli_3z);

    % Subtract the contributions of two-qubit correlations
    % Bipartite, Qubits 1 and 2
    rho_ = rho_ - 1/8*( ...
        exp_pauli_1x_2x * pauli_1x_2x + ...
        exp_pauli_1x_2y * pauli_1x_2y + ...
        exp_pauli_1x_2z * pauli_1x_2z + ...
        exp_pauli_1y_2x * pauli_1y_2x + ...
        exp_pauli_1y_2y * pauli_1y_2y + ...
        exp_pauli_1y_2z * pauli_1y_2z + ...
        exp_pauli_1z_2x * pauli_1z_2x + ...
        exp_pauli_1z_2y * pauli_1z_2y + ...
        exp_pauli_1z_2z * pauli_1z_2z);

    % Bipartite, Qubits 1 and 3
    rho_ = rho_ - 1/8*( ...
        exp_pauli_1x_3x * pauli_1x_3x + ...
        exp_pauli_1x_3y * pauli_1x_3y + ...
        exp_pauli_1x_3z * pauli_1x_3z + ...
        exp_pauli_1y_3x * pauli_1y_3x + ...
        exp_pauli_1y_3y * pauli_1y_3y + ...
        exp_pauli_1y_3z * pauli_1y_3z + ...
        exp_pauli_1z_3x * pauli_1z_3x + ...
        exp_pauli_1z_3y * pauli_1z_3y + ...
        exp_pauli_1z_3z * pauli_1z_3z);

    % Bipartite, Qubits 2 and 3
    rho_ = rho_ - 1/8*( ...
        exp_pauli_2x_3x * pauli_2x_3x + ...
        exp_pauli_2x_3y * pauli_2x_3y + ...
        exp_pauli_2x_3z * pauli_2x_3z + ...
        exp_pauli_2y_3x * pauli_2y_3x + ...
        exp_pauli_2y_3y * pauli_2y_3y + ...
        exp_pauli_2y_3z * pauli_2y_3z + ...
        exp_pauli_2z_3x * pauli_2z_3x + ...
        exp_pauli_2z_3y * pauli_2z_3y + ...
        exp_pauli_2z_3z * pauli_2z_3z);

    % Tripartite, single-body term products
    rho_ = rho_ - 1/8*( ...
        exp_pauli_1x * exp_pauli_2x * exp_pauli_3x * pauli_1x_2x_3x + ...
        exp_pauli_1x * exp_pauli_2x * exp_pauli_3y * pauli_1x_2x_3y + ...
        exp_pauli_1x * exp_pauli_2x * exp_pauli_3z * pauli_1x_2x_3z + ...
        exp_pauli_1x * exp_pauli_2y * exp_pauli_3x * pauli_1x_2y_3x + ...
        exp_pauli_1x * exp_pauli_2y * exp_pauli_3y * pauli_1x_2y_3y + ...
        exp_pauli_1x * exp_pauli_2y * exp_pauli_3z * pauli_1x_2y_3z + ...
        exp_pauli_1x * exp_pauli_2z * exp_pauli_3x * pauli_1x_2z_3x + ...
        exp_pauli_1x * exp_pauli_2z * exp_pauli_3y * pauli_1x_2z_3y + ...
        exp_pauli_1x * exp_pauli_2z * exp_pauli_3z * pauli_1x_2z_3z + ...
        exp_pauli_1y * exp_pauli_2x * exp_pauli_3x * pauli_1y_2x_3x + ...
        exp_pauli_1y * exp_pauli_2x * exp_pauli_3y * pauli_1y_2x_3y + ...
        exp_pauli_1y * exp_pauli_2x * exp_pauli_3z * pauli_1y_2x_3z + ...
        exp_pauli_1y * exp_pauli_2y * exp_pauli_3x * pauli_1y_2y_3x + ...
        exp_pauli_1y * exp_pauli_2y * exp_pauli_3y * pauli_1y_2y_3y + ...
        exp_pauli_1y * exp_pauli_2y * exp_pauli_3z * pauli_1y_2y_3z + ...
        exp_pauli_1y * exp_pauli_2z * exp_pauli_3x * pauli_1y_2z_3x + ...
        exp_pauli_1y * exp_pauli_2z * exp_pauli_3y * pauli_1y_2z_3y + ...
        exp_pauli_1y * exp_pauli_2z * exp_pauli_3z * pauli_1y_2z_3z + ...
        exp_pauli_1z * exp_pauli_2x * exp_pauli_3x * pauli_1z_2x_3x + ...
        exp_pauli_1z * exp_pauli_2x * exp_pauli_3y * pauli_1z_2x_3y + ...
        exp_pauli_1z * exp_pauli_2x * exp_pauli_3z * pauli_1z_2x_3z + ...
        exp_pauli_1z * exp_pauli_2y * exp_pauli_3x * pauli_1z_2y_3x + ...
        exp_pauli_1z * exp_pauli_2y * exp_pauli_3y * pauli_1z_2y_3y + ...
        exp_pauli_1z * exp_pauli_2y * exp_pauli_3z * pauli_1z_2y_3z + ...
        exp_pauli_1z * exp_pauli_2z * exp_pauli_3x * pauli_1z_2z_3x + ...
        exp_pauli_1z * exp_pauli_2z * exp_pauli_3y * pauli_1z_2z_3y + ...
        exp_pauli_1z * exp_pauli_2z * exp_pauli_3z * pauli_1z_2z_3z);

    % Subtract the contributions from connected correlations E_kl *
    % expectation value of a single qubit m. The connected two-qubit
    % correlation is E_kl = <P_k P_l> - <P_k><P_l>
    % E12 x Q3
    rho_ = rho_ - 1/8*( ...
        (exp_pauli_1x_2x - exp_pauli_1x * exp_pauli_2x) * exp_pauli_3x * pauli_1x_2x_3x + ...
        (exp_pauli_1x_2y - exp_pauli_1x * exp_pauli_2y) * exp_pauli_3x * pauli_1x_2y_3x + ...
        (exp_pauli_1x_2z - exp_pauli_1x * exp_pauli_2z) * exp_pauli_3x * pauli_1x_2z_3x + ...
        (exp_pauli_1y_2x - exp_pauli_1y * exp_pauli_2x) * exp_pauli_3x * pauli_1y_2x_3x + ...
        (exp_pauli_1y_2y - exp_pauli_1y * exp_pauli_2y) * exp_pauli_3x * pauli_1y_2y_3x + ...
        (exp_pauli_1y_2z - exp_pauli_1y * exp_pauli_2z) * exp_pauli_3x * pauli_1y_2z_3x + ...
        (exp_pauli_1z_2x - exp_pauli_1z * exp_pauli_2x) * exp_pauli_3x * pauli_1z_2x_3x + ...
        (exp_pauli_1z_2y - exp_pauli_1z * exp_pauli_2y) * exp_pauli_3x * pauli_1z_2y_3x + ...
        (exp_pauli_1z_2z - exp_pauli_1z * exp_pauli_2z) * exp_pauli_3x * pauli_1z_2z_3x + ...
        (exp_pauli_1x_2x - exp_pauli_1x * exp_pauli_2x) * exp_pauli_3y * pauli_1x_2x_3y + ...
        (exp_pauli_1x_2y - exp_pauli_1x * exp_pauli_2y) * exp_pauli_3y * pauli_1x_2y_3y + ...
        (exp_pauli_1x_2z - exp_pauli_1x * exp_pauli_2z) * exp_pauli_3y * pauli_1x_2z_3y + ...
        (exp_pauli_1y_2x - exp_pauli_1y * exp_pauli_2x) * exp_pauli_3y * pauli_1y_2x_3y + ...
        (exp_pauli_1y_2y - exp_pauli_1y * exp_pauli_2y) * exp_pauli_3y * pauli_1y_2y_3y + ...
        (exp_pauli_1y_2z - exp_pauli_1y * exp_pauli_2z) * exp_pauli_3y * pauli_1y_2z_3y + ...
        (exp_pauli_1z_2x - exp_pauli_1z * exp_pauli_2x) * exp_pauli_3y * pauli_1z_2x_3y + ...
        (exp_pauli_1z_2y - exp_pauli_1z * exp_pauli_2y) * exp_pauli_3y * pauli_1z_2y_3y + ...
        (exp_pauli_1z_2z - exp_pauli_1z * exp_pauli_2z) * exp_pauli_3y * pauli_1z_2z_3y + ...
        (exp_pauli_1x_2x - exp_pauli_1x * exp_pauli_2x) * exp_pauli_3z * pauli_1x_2x_3z + ...
        (exp_pauli_1x_2y - exp_pauli_1x * exp_pauli_2y) * exp_pauli_3z * pauli_1x_2y_3z + ...
        (exp_pauli_1x_2z - exp_pauli_1x * exp_pauli_2z) * exp_pauli_3z * pauli_1x_2z_3z + ...
        (exp_pauli_1y_2x - exp_pauli_1y * exp_pauli_2x) * exp_pauli_3z * pauli_1y_2x_3z + ...
        (exp_pauli_1y_2y - exp_pauli_1y * exp_pauli_2y) * exp_pauli_3z * pauli_1y_2y_3z + ...
        (exp_pauli_1y_2z - exp_pauli_1y * exp_pauli_2z) * exp_pauli_3z * pauli_1y_2z_3z + ...
        (exp_pauli_1z_2x - exp_pauli_1z * exp_pauli_2x) * exp_pauli_3z * pauli_1z_2x_3z + ...
        (exp_pauli_1z_2y - exp_pauli_1z * exp_pauli_2y) * exp_pauli_3z * pauli_1z_2y_3z + ...
        (exp_pauli_1z_2z - exp_pauli_1z * exp_pauli_2z) * exp_pauli_3z * pauli_1z_2z_3z);

    % E13 x Q2
    rho_ = rho_ - 1/8*( ...
        (exp_pauli_1x_3x - exp_pauli_1x * exp_pauli_3x) * exp_pauli_2x * pauli_1x_2x_3x + ...
        (exp_pauli_1x_3y - exp_pauli_1x * exp_pauli_3y) * exp_pauli_2x * pauli_1x_2x_3y + ...
        (exp_pauli_1x_3z - exp_pauli_1x * exp_pauli_3z) * exp_pauli_2x * pauli_1x_2x_3z + ...
        (exp_pauli_1y_3x - exp_pauli_1y * exp_pauli_3x) * exp_pauli_2x * pauli_1y_2x_3x + ...
        (exp_pauli_1y_3y - exp_pauli_1y * exp_pauli_3y) * exp_pauli_2x * pauli_1y_2x_3y + ...
        (exp_pauli_1y_3z - exp_pauli_1y * exp_pauli_3z) * exp_pauli_2x * pauli_1y_2x_3z + ...
        (exp_pauli_1z_3x - exp_pauli_1z * exp_pauli_3x) * exp_pauli_2x * pauli_1z_2x_3x + ...
        (exp_pauli_1z_3y - exp_pauli_1z * exp_pauli_3y) * exp_pauli_2x * pauli_1z_2x_3y + ...
        (exp_pauli_1z_3z - exp_pauli_1z * exp_pauli_3z) * exp_pauli_2x * pauli_1z_2x_3z + ...
        (exp_pauli_1x_3x - exp_pauli_1x * exp_pauli_3x) * exp_pauli_2y * pauli_1x_2y_3x + ...
        (exp_pauli_1x_3y - exp_pauli_1x * exp_pauli_3y) * exp_pauli_2y * pauli_1x_2y_3y + ...
        (exp_pauli_1x_3z - exp_pauli_1x * exp_pauli_3z) * exp_pauli_2y * pauli_1x_2y_3z + ...
        (exp_pauli_1y_3x - exp_pauli_1y * exp_pauli_3x) * exp_pauli_2y * pauli_1y_2y_3x + ...
        (exp_pauli_1y_3y - exp_pauli_1y * exp_pauli_3y) * exp_pauli_2y * pauli_1y_2y_3y + ...
        (exp_pauli_1y_3z - exp_pauli_1y * exp_pauli_3z) * exp_pauli_2y * pauli_1y_2y_3z + ...
        (exp_pauli_1z_3x - exp_pauli_1z * exp_pauli_3x) * exp_pauli_2y * pauli_1z_2y_3x + ...
        (exp_pauli_1z_3y - exp_pauli_1z * exp_pauli_3y) * exp_pauli_2y * pauli_1z_2y_3y + ...
        (exp_pauli_1z_3z - exp_pauli_1z * exp_pauli_3z) * exp_pauli_2y * pauli_1z_2y_3z + ...
        (exp_pauli_1x_3x - exp_pauli_1x * exp_pauli_3x) * exp_pauli_2z * pauli_1x_2z_3x + ...
        (exp_pauli_1x_3y - exp_pauli_1x * exp_pauli_3y) * exp_pauli_2z * pauli_1x_2z_3y + ...
        (exp_pauli_1x_3z - exp_pauli_1x * exp_pauli_3z) * exp_pauli_2z * pauli_1x_2z_3z + ...
        (exp_pauli_1y_3x - exp_pauli_1y * exp_pauli_3x) * exp_pauli_2z * pauli_1y_2z_3x + ...
        (exp_pauli_1y_3y - exp_pauli_1y * exp_pauli_3y) * exp_pauli_2z * pauli_1y_2z_3y + ...
        (exp_pauli_1y_3z - exp_pauli_1y * exp_pauli_3z) * exp_pauli_2z * pauli_1y_2z_3z + ...
        (exp_pauli_1z_3x - exp_pauli_1z * exp_pauli_3x) * exp_pauli_2z * pauli_1z_2z_3x + ...
        (exp_pauli_1z_3y - exp_pauli_1z * exp_pauli_3y) * exp_pauli_2z * pauli_1z_2z_3y + ...
        (exp_pauli_1z_3z - exp_pauli_1z * exp_pauli_3z) * exp_pauli_2z * pauli_1z_2z_3z);

    % E23 x Q1
    rho_ = rho_ - 1/8*( ...
        (exp_pauli_2x_3x - exp_pauli_2x * exp_pauli_3x) * exp_pauli_1x * pauli_1x_2x_3x + ...
        (exp_pauli_2x_3y - exp_pauli_2x * exp_pauli_3y) * exp_pauli_1x * pauli_1x_2x_3y + ...
        (exp_pauli_2x_3z - exp_pauli_2x * exp_pauli_3z) * exp_pauli_1x * pauli_1x_2x_3z + ...
        (exp_pauli_2y_3x - exp_pauli_2y * exp_pauli_3x) * exp_pauli_1x * pauli_1x_2y_3x + ...
        (exp_pauli_2y_3y - exp_pauli_2y * exp_pauli_3y) * exp_pauli_1x * pauli_1x_2y_3y + ...
        (exp_pauli_2y_3z - exp_pauli_2y * exp_pauli_3z) * exp_pauli_1x * pauli_1x_2y_3z + ...
        (exp_pauli_2z_3x - exp_pauli_2z * exp_pauli_3x) * exp_pauli_1x * pauli_1x_2z_3x + ...
        (exp_pauli_2z_3y - exp_pauli_2z * exp_pauli_3y) * exp_pauli_1x * pauli_1x_2z_3y + ...
        (exp_pauli_2z_3z - exp_pauli_2z * exp_pauli_3z) * exp_pauli_1x * pauli_1x_2z_3z + ...
        (exp_pauli_2x_3x - exp_pauli_2x * exp_pauli_3x) * exp_pauli_1y * pauli_1y_2x_3x + ...
