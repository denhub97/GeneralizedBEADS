        (exp_pauli_2x_3y - exp_pauli_2x * exp_pauli_3y) * exp_pauli_1z * pauli_1z_2x_3y + ...
        (exp_pauli_2x_3z - exp_pauli_2x * exp_pauli_3z) * exp_pauli_1z * pauli_1z_2x_3z + ...
