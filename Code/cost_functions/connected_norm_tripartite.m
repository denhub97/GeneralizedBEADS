function [EntNorm, States] = connected_norm_tripartite(UCoeff, Eigenstates, RankRho, Dim, pauli_1x, pauli_1y, pauli_1z, ...
                                                       pauli_2x, pauli_2y, pauli_2z, ...
                                                       pauli_3x, pauli_3y, pauli_3z, ...
                                                       pauli_1x_2x, pauli_1x_2y, pauli_1x_2z, ...
                                                       pauli_1y_2x, pauli_1y_2y, pauli_1y_2z, ...
                                                       pauli_1z_2x, pauli_1z_2y, pauli_1z_2z, ...
                                                       pauli_1x_3x, pauli_1x_3y, pauli_1x_3z, ...
                                                       pauli_1y_3x, pauli_1y_3y, pauli_1y_3z, ...
                                                       pauli_1z_3x, pauli_1z_3y, pauli_1z_3z, ...
                                                       pauli_2x_3x, pauli_2x_3y, pauli_2x_3z, ...
                                                       pauli_2y_3x, pauli_2y_3y, pauli_2y_3z, ...
                                                       pauli_2z_3x, pauli_2z_3y, pauli_2z_3z, ...
                                                       pauli_1x_2x_3x, pauli_1x_2x_3y, pauli_1x_2x_3z, ...
                                                       pauli_1x_2y_3x, pauli_1x_2y_3y, pauli_1x_2y_3z, ...
                                                       pauli_1x_2z_3x, pauli_1x_2z_3y, pauli_1x_2z_3z, ...
                                                       pauli_1y_2x_3x, pauli_1y_2x_3y, pauli_1y_2x_3z, ...
                                                       pauli_1y_2y_3x, pauli_1y_2y_3y, pauli_1y_2y_3z, ...
                                                       pauli_1y_2z_3x, pauli_1y_2z_3y, pauli_1y_2z_3z, ...
                                                       pauli_1z_2x_3x, pauli_1z_2x_3y, pauli_1z_2x_3z, ...
                                                       pauli_1z_2y_3x, pauli_1z_2y_3y, pauli_1z_2y_3z, ...
                                                       pauli_1z_2z_3x, pauli_1z_2z_3y, pauli_1z_2z_3z)

    %!!! Cost function for minimizing the tripartite connected correlation
    %    function norm of a pure state decomposition of a tripartite state.
    %    A unitary mixes the eigenstates of the density operator to generate
    %    a new pure state ensemble and the average connected correlation
    %    function norm of the ensemble is computed as the cost. The Pauli
    %    operators are passed in precomputed form to avoid recomputing them
    %    in every function call
    %
    %    input: UCoeff: Coefficients of the Hermitian generator of the
    %                   unitary mixing the eigenstates
    %           Eigenstates: The weighted eigenstates of the density
    %                        operator, stored as columns of the matrix
    %           RankRho: The number of states in the decomposition
    %           Dim: Dimension of the Hilbert space
    %           pauli_*: Precomputed Pauli operators of the 3-qubit
    %                    system, the name encodes the qubits and Pauli
    %                    matrices, e.g., pauli_1x_3z = sigma_x (x) 1 (x)
    %                    sigma_z
    %
    %    output: EntNorm: The average tripartite connected correlation
    %                     function norm of the pure state ensemble
    %            States: The cell array of pure states (including their
    %                    weights) constituting the new decomposition

    % Generate the unitary matrix mixing the eigenstates
    hermitian = generate_hermitian(UCoeff, RankRho);
    unitary = expm(1i*hermitian);

    % With the eigendecomposition as input, the eigenstates are the columns
    % of the Eigenstates matrix. Construct the new states as linear
    % combinations of the eigenstates
    States = cell(RankRho, 1);
    for k = 1:RankRho
        phi_k = zeros(Dim, 1);
        for l = 1:RankRho
            phi_k = phi_k + unitary(k,l) * Eigenstates(:,l);
        end
        States{k,1} = phi_k;
    end

    % Initialize the state weights and connected correlation norms
    list_of_norms = zeros(1, RankRho);
    list_ent_rho_connected = zeros(1, RankRho);

    % Compute the connected correlation norm of each pure state
    for index = 1:RankRho
        % The squared norm of the state is its weight in the ensemble
        list_of_norms(index) = norm(States{index});

        % Normalize the state and compute the corresponding density operator
        norm_vec = States{index}/norm(States{index});
        rho_temp = norm_vec * norm_vec';

        % Tripartite connected correlation function norm of the pure state
        list_ent_rho_connected(index) = cost_connected_tripartite(rho_temp, pauli_1x, pauli_1y, pauli_1z, ...
                                                                  pauli_2x, pauli_2y, pauli_2z, ...
                                                                  pauli_3x, pauli_3y, pauli_3z, ...
                                                                  pauli_1x_2x, pauli_1x_2y, pauli_1x_2z, ...
                                                                  pauli_1y_2x, pauli_1y_2y, pauli_1y_2z, ...
                                                                  pauli_1z_2x, pauli_1z_2y, pauli_1z_2z, ...
                                                                  pauli_1x_3x, pauli_1x_3y, pauli_1x_3z, ...
                                                                  pauli_1y_3x, pauli_1y_3y, pauli_1y_3z, ...
                                                                  pauli_1z_3x, pauli_1z_3y, pauli_1z_3z, ...
                                                                  pauli_2x_3x, pauli_2x_3y, pauli_2x_3z, ...
                                                                  pauli_2y_3x, pauli_2y_3y, pauli_2y_3z, ...
                                                                  pauli_2z_3x, pauli_2z_3y, pauli_2z_3z, ...
                                                                  pauli_1x_2x_3x, pauli_1x_2x_3y, pauli_1x_2x_3z, ...
                                                                  pauli_1x_2y_3x, pauli_1x_2y_3y, pauli_1x_2y_3z, ...
                                                                  pauli_1x_2z_3x, pauli_1x_2z_3y, pauli_1x_2z_3z, ...
                                                                  pauli_1y_2x_3x, pauli_1y_2x_3y, pauli_1y_2x_3z, ...
                                                                  pauli_1y_2y_3x, pauli_1y_2y_3y, pauli_1y_2y_3z, ...
                                                                  pauli_1y_2z_3x, pauli_1y_2z_3y, pauli_1y_2z_3z, ...
                                                                  pauli_1z_2x_3x, pauli_1z_2x_3y, pauli_1z_2x_3z, ...
                                                                  pauli_1z_2y_3x, pauli_1z_2y_3y, pauli_1z_2y_3z, ...
                                                                  pauli_1z_2z_3x, pauli_1z_2z_3y, pauli_1z_2z_3z);
    end

    % Average the connected correlation norms of the states weighted by
    % their probability
    EntNorm = sum((list_of_norms.^2).* list_ent_rho_connected);
end
